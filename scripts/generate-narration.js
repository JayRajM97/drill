#!/usr/bin/env node
// Generates spoken narration for the highlighted drills via ElevenLabs.
//
//   ELEVENLABS_API_KEY=... node scripts/generate-narration.js
//
// One warm voice across all drills (override with ELEVENLABS_VOICE_ID).
// Each chapter is synthesised separately, durations are measured with
// `afinfo`, chunks are stitched into one mp3 per question, and
// src/data/narration.ts is regenerated with static requires + chapter offsets.

const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const SCRIPTS = require('./narration-scripts');

const API_KEY = process.env.ELEVENLABS_API_KEY;
const VOICE_ID = process.env.ELEVENLABS_VOICE_ID || '21m00Tcm4TlvDq8ikWAM'; // "Rachel" — warm, natural
const MODEL_ID = process.env.ELEVENLABS_MODEL_ID || 'eleven_multilingual_v2';

const root = path.join(__dirname, '..');
const outDir = path.join(root, 'assets', 'narration');
fs.mkdirSync(outDir, { recursive: true });

async function tts(text) {
  if (!API_KEY) throw new Error('Chunk missing and no ELEVENLABS_API_KEY set — cannot synthesise.');
  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}?output_format=mp3_44100_128`, {
    method: 'POST',
    headers: { 'xi-api-key': API_KEY, 'content-type': 'application/json' },
    body: JSON.stringify({
      text,
      model_id: MODEL_ID,
      voice_settings: { stability: 0.45, similarity_boost: 0.75, style: 0.25, use_speaker_boost: true },
    }),
  });
  if (!res.ok) throw new Error(`ElevenLabs ${res.status}: ${(await res.text()).slice(0, 300)}`);
  return Buffer.from(await res.arrayBuffer());
}

function durationOf(file) {
  const out = execFileSync('afinfo', [file], { encoding: 'utf8' });
  const m = out.match(/estimated duration:\s*([\d.]+)/);
  if (!m) throw new Error(`afinfo could not read duration of ${file}`);
  return parseFloat(m[1]);
}

// Raw-concatenated MP3s carry the first chunk's header, so CoreAudio thinks
// the whole track is ~20s long (clamped seeks, phantom "finished"). Instead:
// decode every chunk to PCM, splice the samples, encode ONCE to m4a/AAC —
// one authoritative header, sample-accurate chapter offsets.
const RATE = 44100;
const CHANNELS = 2;
const BYTES_PER_FRAME = CHANNELS * 2; // 16-bit

function decodeToPcm(mp3Path) {
  const wav = `${mp3Path}.wav`;
  execFileSync('afconvert', ['-f', 'WAVE', '-d', `LEI16@${RATE}`, '-c', String(CHANNELS), mp3Path, wav]);
  const buf = fs.readFileSync(wav);
  const idx = buf.indexOf(Buffer.from('data'));
  if (idx < 0) throw new Error(`no data chunk in ${wav}`);
  const size = buf.readUInt32LE(idx + 4);
  const pcm = buf.subarray(idx + 8, idx + 8 + size);
  fs.unlinkSync(wav);
  return pcm;
}

function writeWav(pcm, outPath) {
  const header = Buffer.alloc(44);
  header.write('RIFF', 0);
  header.writeUInt32LE(36 + pcm.length, 4);
  header.write('WAVE', 8);
  header.write('fmt ', 12);
  header.writeUInt32LE(16, 16);
  header.writeUInt16LE(1, 20); // PCM
  header.writeUInt16LE(CHANNELS, 22);
  header.writeUInt32LE(RATE, 24);
  header.writeUInt32LE(RATE * BYTES_PER_FRAME, 28);
  header.writeUInt16LE(BYTES_PER_FRAME, 32);
  header.writeUInt16LE(16, 34);
  header.write('data', 36);
  header.writeUInt32LE(pcm.length, 40);
  fs.writeFileSync(outPath, Buffer.concat([header, pcm]));
}

(async () => {
  const registry = [];
  for (const [id, q] of Object.entries(SCRIPTS)) {
    console.log(`\n▸ ${id} (${q.chapters.length} chapters)`);
    const chapters = [];
    let offset = 0;
    const pcms = [];
    for (const [i, ch] of q.chapters.entries()) {
      const chunk = path.join(outDir, `.${id}.${i}.mp3`);
      if (!fs.existsSync(chunk)) {
        process.stdout.write(`  ${i + 1}. ${ch.label} … `);
        fs.writeFileSync(chunk, await tts(ch.text));
        console.log('ok');
      } else {
        console.log(`  ${i + 1}. ${ch.label} (cached)`);
      }
      const pcm = decodeToPcm(chunk);
      const dur = pcm.length / BYTES_PER_FRAME / RATE;
      chapters.push({ label: ch.label, at: Math.round(offset * 10) / 10, ...(ch.target ? { target: ch.target } : {}) });
      offset += dur;
      pcms.push(pcm);
    }
    const combinedWav = path.join(outDir, `.${id}.wav`);
    writeWav(Buffer.concat(pcms), combinedWav);
    const finalPath = path.join(outDir, `${id}.m4a`);
    if (fs.existsSync(finalPath)) fs.unlinkSync(finalPath);
    execFileSync('afconvert', ['-f', 'm4af', '-d', 'aac', '-b', '128000', combinedWav, finalPath]);
    fs.unlinkSync(combinedWav);
    const check = durationOf(finalPath);
    console.log(`  → ${path.relative(root, finalPath)} (${Math.round(offset)}s expected, container says ${Math.round(check)}s)`);
    if (Math.abs(check - offset) > 2) throw new Error(`duration mismatch for ${id}: ${check} vs ${offset}`);
    registry.push({ id, chapters, duration: Math.round(offset) });
  }

  const ts = `// Generated by scripts/generate-narration.js — do not edit by hand.
// One narration track per highlighted drill; chapters map moments in the
// audio to the sections of the answer.

export interface NarrationChapter {
  label: string;
  /** Start of this chapter in seconds. */
  at: number;
  /** Which deck card this chapter narrates (resolved at runtime). */
  target?: { section: string; title?: string };
}

export interface Narration {
  source: number; // static require() of the bundled mp3
  duration: number;
  chapters: NarrationChapter[];
}

export const NARRATION: Record<string, Narration> = {
${registry
  .map(
    (r) => `  '${r.id}': {
    source: require('../../assets/narration/${r.id}.m4a'),
    duration: ${r.duration},
    chapters: ${JSON.stringify(r.chapters)},
  },`,
  )
  .join('\n')}
};
`;
  fs.writeFileSync(path.join(root, 'src/data/narration.ts'), ts);
  console.log(`\nwrote src/data/narration.ts with ${registry.length} narrations`);
})();
