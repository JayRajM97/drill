// Generates targets/widget/Questions.swift from the question data so the iOS
// home-screen widget can rotate through real questions with zero app <-> widget
// data sharing. Run: node scripts/generate-widget-questions.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const enriched = JSON.parse(fs.readFileSync(path.join(root, 'assets/seed/enriched-notion.json'), 'utf8'));
const curatedSrc = fs.readFileSync(path.join(root, 'src/data/curated.ts'), 'utf8');

const rows = [];
for (const q of enriched) {
  rows.push({ id: q.id, title: q.title, category: q.categories[0], difficulty: q.difficulty });
}
const re = /id: '([^']+)',\s*\n\s*title:\s*\n?\s*(['"])([\s\S]*?)\2,\s*\n\s*categories: \['([^']+)'[^\]]*\],[\s\S]*?difficulty: '([^']+)'/g;
let m;
while ((m = re.exec(curatedSrc))) {
  rows.push({ id: m[1], title: m[3].replace(/\\'/g, "'").replace(/\s+/g, ' ').trim(), category: m[4], difficulty: m[5] });
}
const seen = new Set();
const pool = rows.filter((r) => (seen.has(r.id) ? false : (seen.add(r.id), true)));

// Key numbers for the small/medium widget: simple (non-composite) facts with
// short values, extracted from src/data/numbers.ts f('id','label','value',…) calls.
const numbersSrc = fs.readFileSync(path.join(root, 'src/data/numbers.ts'), 'utf8');
const numbers = [];
const nre = /f\(\s*'([^']+)',\s*'((?:[^'\\]|\\.)*)',\s*'((?:[^'\\]|\\.)*)'/g;
let nm;
while ((nm = nre.exec(numbersSrc))) {
  const label = nm[2].replace(/\\'/g, "'");
  const value = nm[3].replace(/\\'/g, "'");
  if (value.length <= 16 && label.length <= 40) numbers.push({ id: nm[1], label, value });
}

const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
const swift = `// Generated by scripts/generate-widget-questions.js — do not edit by hand.
// ${pool.length} questions + ${numbers.length} key numbers bundled into the widget.

struct WidgetQuestion {
    let id: String
    let title: String
    let category: String
    let difficulty: String
}

struct WidgetNumber {
    let id: String
    let label: String
    let value: String
}

let ALL_QUESTIONS: [WidgetQuestion] = [
${pool.map((r) => `    WidgetQuestion(id: "${esc(r.id)}", title: "${esc(r.title)}", category: "${esc(r.category)}", difficulty: "${esc(r.difficulty)}"),`).join('\n')}
]

let ALL_NUMBERS: [WidgetNumber] = [
${numbers.map((r) => `    WidgetNumber(id: "${esc(r.id)}", label: "${esc(r.label)}", value: "${esc(r.value)}"),`).join('\n')}
]
`;
fs.writeFileSync(path.join(root, 'targets/widget/Questions.swift'), swift);
console.log(`wrote ${pool.length} questions + ${numbers.length} numbers to targets/widget/Questions.swift`);
